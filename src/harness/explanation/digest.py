"""Выжимка для модели: числа, отданные в промпт, и они же — разрешённые в ответе.

Ключевой инвариант задачи — «числа в тексте модели обязаны быть подмножеством
чисел из расчёта» — опирается на то, что величина попадает в промпт и в список
разрешённых ОДНОЙ записью: `book.bb(x)` и форматирует, и разрешает.

Дисциплина при этом остаётся на авторе выжимки: **величина не печатается мимо
книги**. Реестр этого не гарантирует и гарантировать не может — обычная
f-строка ему не подотчётна, и первый живой прогон отбраковал текст ровно за
такое число (цифра внутри пояснения к допущению, показанного модели и не
зарегистрированного). Ловят нарушение тесты выжимок (`test_verdict_text.py`,
`test_tournament_text.py`): они вычитают из чисел готового промпта разрешённые
и требуют пустоты — на фикстурах, где цифры есть и в пояснении, и в классе руки.

Идентификаторы (номер точки, `dp_index`) через книгу НЕ идут: они не величины,
а регистрация делала бы 0 и 1 разрешёнными в любом разборе.

`prose` — исключение для текста, который собрал код, а не модель (реплей руки):
регистрируется каждое его число.
"""

from __future__ import annotations

from harness.explanation.faithfulness import numbers_in

__all__ = ["NumberBook"]


class NumberBook:
    """Числа промпта: форматирует для модели и запоминает как разрешённые.

    Формат намеренно машинный (`-1.2`, `34.2`, `17`), без единиц и типографики:
    единицу («bb», «%») дописывает текст выжимки рядом, а модель копирует само
    число. Знак — обычный дефис: модели проще воспроизвести его точно, а
    проверка (`faithfulness.numbers_in`) понимает оба вида минуса.
    """

    def __init__(self) -> None:
        self._allowed: set[float] = set()

    @property
    def allowed(self) -> frozenset[float]:
        return frozenset(self._allowed)

    def bb(self, value: float) -> str:
        """Величина в bb с одним знаком после точки — та же точность, что у изложения."""
        rounded = round(value, 1)
        self._allowed.add(rounded)
        return f"{rounded:.1f}"

    def pct(self, value: float, *, trim: bool = False) -> str:
        """Доля в процентах, одним знаком: модель обязана взять её готовой.

        `trim` — целое без «.0» (`24`, но `38.9`): так печатают выходы агента.
        Разрешается то же значение, так что «24» и «24.0» в ответе равны
        (`test_whole_percents_go_without_a_trailing_zero`).
        """
        rounded = round(value, 1)
        self._allowed.add(rounded)
        text = f"{rounded:.1f}"
        return text.removesuffix(".0") if trim else text

    def count(self, value: int) -> str:
        """Штуки (раздачи, повторы, уровни) — целым числом."""
        self._allowed.add(float(value))
        return str(value)

    def token(self, value: str) -> str:
        """Строка, внутри которой есть цифры (номер раздачи, идентификатор).

        Регистрируется как разрешённое число каждая группа цифр: модель вправе
        сослаться на раздачу по номеру, и проверка не должна считать её выдумкой.
        """
        current = ""
        for char in value + " ":
            if char.isdigit():
                current += char
            elif current:
                self._allowed.add(float(current))
                current = ""
        return value

    def prose(self, text: str) -> str:
        """Текст, собранный КОДОМ из фактов руки (реплей): каждое его число разрешено.

        Для готовых строк, а не для величин: у величины свой формат (`bb`, `pct`,
        `count`). Модельный текст сюда не попадает никогда — регистрация сделала
        бы разрешённым выдуманное (`test_prose_registers_every_number_of_a_code_built_text`).
        """
        self._allowed.update(numbers_in(text))
        return text
