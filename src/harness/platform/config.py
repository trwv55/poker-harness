"""Конфигурация провайдер-слоя и инфраструктуры (спека §7): числа и строки, которые
меняются по окружению (модель, лимиты, DSN, токен бота), читаются один раз из
`os.environ` и дальше передаются значением — ни `llm.py`, ни `limiter.py` не читают
`os.environ` сами. Это то же самое разделение, что и у `session_factory` в `queue.py`
(задача 15): код пакета `platform` работает с уже готовыми значениями, а не с их
источником, и его тесты подставляют `Config` руками, не трогая переменные окружения
процесса.

Смена модели — это смена строки конфига, а не правка кода (спека §7: "требование
независимости от вендора — выполняется конфигом"), поэтому `llm_vision_model`/
`llm_verdict_model` не валидируются здесь на конкретный список провайдеров — формат
`"<provider>:<model>"` целиком в ведении PydanticAI (`Agent(model=...)`, 20+
провайдеров), а дублировать его список констант в этом файле означало бы рассинхрон
при каждом обновлении зависимости.
"""

from __future__ import annotations

import os
from dataclasses import dataclass


class EnvVarError(Exception):
    """Конфигурация не годится: переменная не задана либо задана мусором.

    Общая база двух отказов (добавлена в раунде 2 ревью задачи 20) нужна не для
    красоты иерархии, а потому что точки входа ловят конфигурационный отказ
    ОДНИМ `except` и печатают одну строку вместо трассировки. Пока класс был
    один, `WORKER_CONCURRENCY=abc` и `LLM_MAX_CONCURRENCY=четыре` давали голый
    `ValueError` — для оператора это неотличимо от той самой поломки, которую
    раунд 1 и чинил: контейнер в цикле рестартов сыплет стеком вместо того,
    чтобы назвать переменную.
    """


class MissingEnvVar(EnvVarError):
    """Обязательная переменная окружения не задана. Отдельно от `KeyError`
    голого `os.environ[...]` — сообщение называет саму переменную и то, что она
    обязательна, а не индекс в отображении, который ничего не говорит о причине.
    """


class InvalidEnvVar(EnvVarError):
    """Переменная задана, но значение не разбирается (целое число из букв).

    Отдельный класс, а не `MissingEnvVar`: «не задана» и «задана неверно» —
    разные действия оператора, и сообщение обязано их различать, иначе он будет
    искать пустую строку там, где на самом деле опечатка.
    """


def _require(name: str) -> str:
    value = os.environ.get(name)
    if not value:
        raise MissingEnvVar(f"обязательная переменная окружения {name} не задана")
    return value


def _parse_int(name: str, raw: str) -> int:
    """Разбор целого В ОДНОМ МЕСТЕ — сюда сходятся и обязательные переменные, и
    необязательные. Так `int()` не остаётся ни на одной точке вызова: иначе
    честное сообщение получала бы та переменная, которой повезло с call site,
    а остальные — трассировку (ревью задачи 20, раунд 2).
    """
    try:
        return int(raw)
    except ValueError as exc:
        raise InvalidEnvVar(
            f"переменная окружения {name} должна быть целым числом, а не {raw!r}"
        ) from exc


def _require_int(name: str) -> int:
    return _parse_int(name, _require(name))


def optional_env(name: str, default: str) -> str:
    """Необязательная переменная окружения, где ПУСТАЯ строка равна незаданной.

    Существует не ради симметрии с `_require`, а из-за конкретного отказа
    (ревью задачи 20): `env_file` в Docker Compose ставит строку
    `WORKER_CONCURRENCY=` как ПУСТОЕ ЗНАЧЕНИЕ, а не как отсутствие переменной.
    Голый `os.environ.get(name, default)` в этом случае вернёт `""`, дефолт не
    применится — и `int("")` роняет воркер трассировкой, а `restart:
    unless-stopped` превращает это в цикл рестартов. Путь к отказу — ровно тот,
    который предписывает наш собственный README: `cp .env.example .env`.

    Семантика та же, что у `_require` выше («пустое значит незаданное»), и
    держать её в одном месте важнее, чем сэкономить функцию: следующая
    необязательная переменная получит её бесплатно, а не повторит ту же ошибку.
    """
    return os.environ.get(name) or default


def optional_int(name: str, default: int) -> int:
    """Необязательная ЦЕЛОЧИСЛЕННАЯ переменная окружения.

    Существует затем, чтобы `int(...)` не жил на точке вызова: `int(optional_env
    (...))` в воркере разбирал число сам и на `WORKER_CONCURRENCY=abc` давал
    голый `ValueError` с трассировкой — тот же симптом, что и в раунде 1, только
    другой триггер. Здесь пустое значение по-прежнему считается незаданным
    (см. `optional_env`), а непустое разбирается общим `_parse_int` и потому
    ошибается так же внятно, как обязательные переменные.
    """
    raw = os.environ.get(name)
    if not raw:
        return default
    return _parse_int(name, raw)


@dataclass(frozen=True, slots=True)
class Config:
    """Снимок конфигурации на момент запуска процесса — сам окружение не читает
    (см. модульный докстринг): значения приходят в конструктор, поэтому тесты
    собирают `Config` напрямую, без правки `os.environ`.

    `from_env()` — единственная точка, где окружение читается ДЛЯ ЭТОГО СНИМКА.
    Не единственная во всём модуле (round 5, Item K.3: так здесь и было
    написано, и это неверно): к `os.environ` обращаются `_require`,
    `optional_env` и `optional_int` — первый по требованию самой `from_env`, два
    других обслуживают переменные, которых в снимке нет вовсе
    (`WORKER_CONCURRENCY`, `DATA_DIR` — тюнинг одного процесса, а не общий
    конфиг, см. их докстринги).
    """

    llm_vision_model: str
    llm_verdict_model: str
    llm_max_concurrency: int
    llm_max_per_minute: int
    database_url: str
    telegram_token: str

    @classmethod
    def from_env(cls) -> Config:
        return cls(
            llm_vision_model=_require("LLM_VISION_MODEL"),
            llm_verdict_model=_require("LLM_VERDICT_MODEL"),
            llm_max_concurrency=_require_int("LLM_MAX_CONCURRENCY"),
            llm_max_per_minute=_require_int("LLM_MAX_PER_MINUTE"),
            database_url=_require("DATABASE_URL"),
            telegram_token=_require("TELEGRAM_TOKEN"),
        )
