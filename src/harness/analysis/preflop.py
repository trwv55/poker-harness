# оставалась БЕЗ вердикта с причиной «одного надёжного числа здесь нет» — а это
# не вердикт, а отказ от него: находка верна (EV и правда зависит от допущения),
# но упаковка прятала три полезные вещи — знак и порядок величины, ширину
# интервала как меру маргинальности и потолок цены ошибки. Теперь точка
# получает вердикт «около нуля» вместе с интервалом (`EvInterval`), а цена
# такой точки — ноль: раз оба варианта допустимы, упрекать не за что (то же
# правило самого мягкого упрёка, что и у `_BEST_DEPENDS_ON_BEHIND`).
#
# Исключение одно — форма, где ширину не угадывают, а берут из равновесия
# (хедз-ап SB против BB): там вердикт держит равновесие, а не интервал, и
# `zone_for` ставит такой точке `strict`. Закреплено
# `test_an_interval_across_zero_gets_the_near_zero_verdict_with_a_ceiling` и
# `test_hu_equilibrium_shape_is_strict_even_when_bracket_unstable`.
_BOTH_ACCEPTABLE = "около нуля, оба варианта допустимы"

# Решатель равновесия не достиг порогов остановки (`DidNotConverge`). Профиль,
# который не сошёлся, — это не «примерно равновесие», а неизвестно что, и цену
# шова по нему не считаем. Отказ снимает одну точку, а не роняет разбор файла.
_NO_EQUILIBRIUM = (
    "равновесие этого стола посчитать не удалось, а называть цену шова по "
    "недосчитанной модели мы не будем"
)

# Потолок памяти мультивей-кэша эквити. Воркер живёт долго и разбирает турнир за
# турниром, поэтому кэш без границы — утечка. При переполнении он сбрасывается
# целиком: вытеснять по возрасту незачем, повторный расчёт стоит доли секунды
# (при тёплом дисковом кэше — см. ниже) или единиц секунд (при холодном), а
# детерминизм от сброса не страдает — те же входы дают то же число.
_EQUITY_MEMO_LIMIT = 4096

_HeroCombo = tuple[str, str]
_RangeKey = tuple[tuple[str, float], ...]
_equity_memo: dict[tuple[_HeroCombo, tuple[_RangeKey, ...]], float] = {}

# Сид Монте-Карло зафиксирован здесь явно (а не оставлен дефолтом
# `equity_vs_ranges`), потому что отпечаток дискового кэша обязан включать его:
# скрытая смена сида в другом месте молча сделала бы прочитанный с диска ответ
# соответствующим другому (недетерминированному относительно текущего вызова)
# розыгрышу.
_EQUITY_MC_SEED = 42

# Дисковый кэш эквити мультивея (задача 13, рулинг владельца: измерение показало
# 47.6с на одну точку с несколькими живыми позади — 78% времени дневной
# фикстуры в восьми точках). `_equity_memo` выше уже ловит повтор ВНУТРИ одного
# прогона (см. его докстринг) и на дневной фикстуре даёт 81% попаданий, но
# каждый новый процесс (новый прогон тестов, новый воркер) начинает с нуля —
# 829 оставшихся промахов пересчитываются заново при каждом холодном старте.
# Файл ниже переживает процесс: тот же принцип, что и у `nash_hu` (см.
# `_nash_solution`/`_read_nash_cache`) — JSON-словарь по округлённому отпечатку
# входов, best-effort запись (не мешает работе, если каталог только для чтения).
#
# Сэмплер детерминирован по сиду (`equity.py`, докстринг модуля): одни и те же
# карты героя, диапазоны, число итераций и сид всегда дают одно и то же число.
# Поэтому кэш точный — он меняет скорость, а не ответ, и не требует TTL или
# инвалидации по времени; инвалидируется только явной сменой версии/итераций
# в отпечатке.
_EQUITY_CACHE_VERSION = 1
_EQUITY_CACHE_PATH = Path(__file__).parent / "tools" / "data" / "equity_mc_cache.json"
_disk_equity_cache: dict[str, float] | None = None  # ленивая загрузка, None = не читали


def _equity_cache_fingerprint() -> str:
    """Отпечаток входов дискового кэша: версия, итерации, сид.

    Без него смена `_MULTIWAY_ITERATIONS` (точность оценки) или сида молча
    отдавала бы число, посчитанное на ДРУГИХ входах, как если бы оно отвечало
    на текущий запрос — тот же класс ошибки, что `_nash_fingerprint` закрывает
    для равновесий.
    """
    return f"v{_EQUITY_CACHE_VERSION}-it{_MULTIWAY_ITERATIONS}-seed{_EQUITY_MC_SEED}"


def _equity_cache_key(hero: _HeroCombo, range_key: tuple[_RangeKey, ...]) -> str:
    """Стабильный строковый ключ для JSON: хеш канонического представления входа.

    Сами карты и диапазоны в ключ не годятся напрямую (JSON-ключи — только
    строки, а вложенные кортежи неудобно сериализовать обратимо), поэтому вход
    хешируется — так же, как `_nash_fingerprint` хеширует таблицу эквити.
    """
    payload = {"hero": list(hero), "ranges": [[[c, w] for c, w in r] for r in range_key]}
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return sha256(blob.encode("utf-8")).hexdigest()


def _load_disk_equity_cache() -> dict[str, float]:
    global _disk_equity_cache
    if _disk_equity_cache is not None:
        return _disk_equity_cache
    try:
        payload = json.loads(_EQUITY_CACHE_PATH.read_text(encoding="utf-8"))
        if payload.get("fingerprint") == _equity_cache_fingerprint():
            _disk_equity_cache = dict(payload.get("entries", {}))
        else:
            _disk_equity_cache = {}
    except (OSError, ValueError, TypeError, AttributeError):
        _disk_equity_cache = {}
    return _disk_equity_cache


def _save_disk_equity_cache() -> None:
    """Пишет накопленный кэш на диск — вызывается один раз при выходе процесса.

    Одна запись всего файла в конце, а не на каждый промах: сериализовать и
    писать словарь целиком на каждую новую запись стоило бы O(n^2) на весь
    прогон при тысячах записей. Кэш — ускорение, а не источник истины (как и
    `_write_nash_cache`), поэтому ошибка записи (например, каталог пакета
    только для чтения) молча проглатывается, а не роняет разбор.
    """
    if _disk_equity_cache is None:
        return
    try:
        _EQUITY_CACHE_PATH.parent.mkdir(parents=True, exist_ok=True)
        _EQUITY_CACHE_PATH.write_text(
            json.dumps(
                {"fingerprint": _equity_cache_fingerprint(), "entries": _disk_equity_cache},
                ensure_ascii=False,
            ),
            encoding="utf-8",
        )
    except OSError:
        pass  # тот же принцип, что и у `_write_nash_cache`: без кэша, но не падаем


atexit.register(_save_disk_equity_cache)


def equity_cache_fingerprint() -> str:
    """Публичная обёртка над `_equity_cache_fingerprint()` — задача 18 использует
    её как пространство имён ключей в `calc_cache` (Postgres), тем же приёмом,
    что и дисковый кэш выше: смена версии/итераций/сида меняет отпечаток, и
    старые строки просто перестают совпадать по префиксу, вместо того чтобы
    молча выдать число, посчитанное на других входах, за ответ на текущий
    запрос.
    """
    return _equity_cache_fingerprint()


def equity_cache_seed(entries: Mapping[str, float]) -> None:
    """Домешать во внутрипроцессный кэш строки, посчитанные ДРУГИМ процессом
    (задача 18, контроллерский рулинг п.1: `calc_cache` в Postgres — общее
    хранилище между воркерами, дисковый файл — только между прогонами ОДНОГО
    процесса). Вызывающий (воркер) читает `calc_cache` ДО передачи руки в
    процессный пул и сюда сеет результат — дальше `_model_equity` видит эти
    записи как обычные попадания кэша, не отличая их от посчитанных на месте.

    `_load_disk_equity_cache()` вызывается первой, чтобы не затереть уже
    прочитанное с диска: сид — это ДОБАВКА к существующему кэшу процесса, а не
    его замена.
    """
    _load_disk_equity_cache().update(entries)


def equity_cache_export() -> dict[str, float]:
    """Снимок текущего внутрипроцессного кэша целиком — задача 18 сохраняет его
    обратно в `calc_cache` после скана (`ON CONFLICT DO NOTHING`, см.
    `CalcCacheRepo`: значения детерминированы, переписывать существующую
    строку нечем). Копия, а не сама ссылка — вызывающий кладёт результат в
    аргумент `run_in_executor`, который пересекает границу процесса
    сериализацией, а не разделяемой памятью, и мутация оригинала после
    экспорта не имеет права тихо просочиться в уже отправленный снимок.
    """
    return dict(_load_disk_equity_cache())


def _model_equity(hero: _HeroCombo, ranges: Sequence[Range]) -> float:
    """Эквити героя против набора диапазонов: таблицей, где она есть, иначе Монте-Карло.

    Против одного диапазона ответ берётся из той же таблицы 169x169, на которой
    посчитано само равновесие: считать Монте-Карло то, что уже посчитано точнее,
    значит вносить шум и расходиться с диапазоном, против которого судим.
    Мультивей-веток в таблице нет — они идут через сэмплер, и их результат
    запоминается дважды: в памяти на весь процесс (`_equity_memo`) и на диске
    между процессами (`_disk_equity_cache`, см. докстринг выше) — `shove_ev_bb`
    перебирает 2^n подмножеств, но разных наборов диапазонов среди них всего
    единицы, а те же наборы регулярно повторяются между руками одного скана и
    между отдельными прогонами.
    """
    if len(ranges) == 1:
        return equity_vs_range_classes(class_of(*hero), ranges[0])
    range_key = tuple(sorted(tuple(sorted(r.weights.items())) for r in ranges))
    key = (hero, range_key)
    cached = _equity_memo.get(key)
    if cached is None:
        disk_cache = _load_disk_equity_cache()
        disk_key = _equity_cache_key(hero, range_key)
        cached = disk_cache.get(disk_key)
        if cached is None:
            cached = equity_vs_ranges(
                hero, list(ranges), iterations=_MULTIWAY_ITERATIONS, seed=_EQUITY_MC_SEED
            )
            disk_cache[disk_key] = cached
        if len(_equity_memo) >= _EQUITY_MEMO_LIMIT:
            _equity_memo.clear()
        _equity_memo[key] = cached
    return cached


def _depth_key(depth_bb: float) -> float:
    """Глубина, округлённая до сетки и зажатая в окно осмысленности пуш-фолда."""
    clamped = min(max(depth_bb, _MIN_MODEL_DEPTH_BB), _MAX_MODEL_DEPTH_BB)
    return round(clamped / _DEPTH_STEP_BB) * _DEPTH_STEP_BB


def _equilibrium_depth(depth_bb: float) -> float | None:
    """Та же сетка, но без зажима: вне окна равновесие не выдаётся за равновесие."""
    key = round(depth_bb / _DEPTH_STEP_BB) * _DEPTH_STEP_BB
    if not _MIN_MODEL_DEPTH_BB <= key <= _MAX_MODEL_DEPTH_BB:
        return None
    return key


def _dead_key(dead_bb: float) -> float:
    """Мёртвые деньги, округлённые до сетки и зажатые окном `nash_hu`.

    Верхний зажим — деградация вместо падения. Гвард в `nash_hu` стоит против
    перепутанных единиц (фишки вместо bb); здесь величина считается из настоящих
    анте и bb, перепутать нечего, поэтому структура с невероятным анте должна
    дать самое широкое равновесие из посчитанных, а не уронить разбор турнира.
    На фикстурах максимум — 1.2bb при потолке 5.
    """
    clamped = min(max(dead_bb, 0.0), MAX_DEAD_EXTRA_BB)
    return round(clamped / _DEAD_STEP_BB) * _DEAD_STEP_BB


def _table_dead_bb(state: TableState) -> float:
    """Сумма анте всего стола в bb — мёртвые деньги решаемого равновесия.

    Считаются анте ВСЕХ мест, а не только живых: анте спасовавших остаётся в
    банке и разыгрывается наравне с блайндами. Именно эта величина и была
    потеряна в игре без анте — на фикстуре она даёт 0.875bb против 1.5bb
    блайндов, и равновесие без неё оказывается на 12-14 п.п. комбо теснее того,
    в которое играет пользователь.
    """
    return _dead_key(sum(seat.ante for seat in state.seats) / state.bb)


def _table_equilibrium(
    state: TableState, behind: Sequence[SeatSnapshot], bb: int
) -> MultiwaySolution:
    """Равновесие подыгры «шов героя в неоткрытый банк» для ЭТОГО состава стола.

    Деньги берутся ровно те же, что уходят в `shove_ev_bb`: банк `pot_before`,
    посты каждого места, урезанные потолком героя, и остатки за спиной. Одна
    точка решения стоит одного решения независимо от того, сколько раз её
    посчитали: результат запоминает сам решатель.

    Возвращается вся связка «шов + коллы»: колл-диапазон является наилучшим
    ответом на диапазон шова того же решения, и разрывать пару нельзя.
    """
    ceiling = state.hero.stack
    return unopened_shove_equilibrium(
        MultiwaySeat(
            posted_bb=state.hero.contributed / bb, behind_bb=state.hero.behind / bb
        ),
        [
            MultiwaySeat(
                posted_bb=min(seat.contributed, ceiling) / bb, behind_bb=seat.behind / bb
            )
            for seat in behind
        ],
        state.pot_before / bb,
    )


def _push_model(depth_bb: float, dead_bb: float) -> Range:
    """Модель диапазона шова игрока такой глубины — пуш-сторона равновесия."""
    return nash_hu(_depth_key(depth_bb), dead_extra_bb=dead_bb)[0]


def _checksum_detail(callers: Sequence[CallerModel], hero_cls: str) -> dict[str, object]:
    """Числа контрольной суммы — в `detail` каждой точки о шове в неоткрытый банк.

    Стоят и у судимой точки, и у снятой: по ним видно, насколько модель стола
    разошлась с проверкой и чем именно точка снята. Игроку не показываются
    ничем (см. `_unjudged`).
    """
    probs = [default_call_prob(caller, hero_cls) for caller in callers]
    return {
        "p_all_fold": round(prod(1.0 - p for p in probs), 6),
        "expected_callers": round(sum(probs), 4),
    }


def _model_checksum(callers: Sequence[CallerModel], hero_cls: str) -> str:
    """Причина снять вердикт о шове, если модель колла описывает не этот стол.

    Пустая строка означает, что проверка пройдена. Считается по тем же
    `CallerModel`, что уходят в `shove_ev_bb`, и той же вероятностью колла
    (`default_call_prob`), которой считается сама EV: `p_all_fold = Π(1 − p_i)`,
    `expected_callers = Σ p_i`. Пороги — `_MIN_ALL_FOLD_PROB` и
    `_MAX_EXPECTED_CALLERS`.

    Причина написана для игрока (SESSIONS_UX): что именно не так с моделью и
    почему цены не будет, без внутренних терминов. Закреплено
    `test_a_shove_the_model_says_is_almost_always_answered_gets_no_verdict` и
    `test_a_realistic_calling_model_passes_the_checksum`.
    """
    probs = [default_call_prob(caller, hero_cls) for caller in callers]
    p_all_fold = prod(1.0 - p for p in probs)
    expected_callers = sum(probs)
    if p_all_fold >= _MIN_ALL_FOLD_PROB and expected_callers <= _MAX_EXPECTED_CALLERS:
        return ""
    return (
        f"по нашей модели такой шов проходит без ответа лишь в {p_all_fold:.0%} случаев, "
        f"а отвечают на него в среднем {expected_callers:.1f} из {len(probs)} — для этого "
        f"стола модель не годится, и цену шова по ней мы не считаем"
    )


def _average_range(ranges: Sequence[Range]) -> Range:
    """Диапазон «среднего» оппонента — то, что показывается игроку как допущение."""
    if len(ranges) == 1:
        return ranges[0]
    classes = {cls for rng in ranges for cls in rng.weights}
    weights = {cls: sum(rng.weight(cls) for rng in ranges) / len(ranges) for cls in classes}
    return Range(weights={cls: round(w, 6) for cls, w in weights.items() if w > 0.0})


def zone_for(
    best_tight: str,
    best_wide: str,
    *,
    live_total: int,
    equilibrium: bool = True,
    best_model: str | None = None,
    best_interior: Sequence[str] = (),
    best_behind: Sequence[str] = (),
    unmodelled: str = "",
) -> tuple[Zone, str]:
    """Зона доверия точки и причина, по которой она такая (спека §5.5).

    Здесь решается зона целиком: снаружи не осталось ни одного места, где её
    можно было бы переопределить. Это требование к читаемости, а не к стилю —
    изложение (задача 21) обязано объяснить игроку, почему вывод помечен так, а
    не иначе, и собирать объяснение из двух источников оно не должно.

    Что означают аргументы:

    * `equilibrium` при `live_total == 2` — настоящий хедз-ап либо SB против BB
      после пасов: колл-диапазон взят из равновесия, угадывать нечего. Флаг нужен
      потому, что двое живых сами по себе равновесия не дают: шов из ранней
      позиции, до которого спасовали все, кроме большого блайнда, оставляет за
      столом двоих, но это уже другая игра — там мёртвый малый блайнд и другой
      шовер;
    * `best_tight`, `best_interior`, `best_wide` — вердикты на СЕТКЕ ширин
      диапазона, от узкого конца до широкого. Опрашивается интервал, а не два его
      конца: EV по ширине не обязана быть монотонной (замер — в докстринге
      `_SHOVE_CALL_WIDTH_MULTIPLIERS`). Ветка закреплена
      `test_zone_for_notices_a_reversal_inside_the_interval`;
    * `best_model` — вердикт самой модели. Он обязан входить в проверку: точки
      вилки — это диапазоны, построенные по ЗАДАННОЙ ШИРИНЕ, а модель шириной не
      задана (веса в ней дробные, и порядок классов у неё свой), поэтому её
      вердикт может не совпасть ни с одной точкой вилки — и тогда концы совпали
      бы между собой, противореча выданному вердикту;
    * `best_behind` — вердикты по оси «живые за героем тоже входят в банк».
      Ось существует там, где этих игроков в модели нет вовсе;
    * `unmodelled` — непустая строка означает, что какое-то измерение задачи в
      модель не попало вообще (живых позади больше, чем модель способна
      перебрать). Тогда проверять нечего и `strict` заявлять не о чем.
    """
    if unmodelled:
        return Zone.ASSUMING, unmodelled
    if live_total == 2 and equilibrium:
        return Zone.STRICT, "хедз-ап SB против BB: колл-диапазон взят из равновесия пуш-фолда"

    by_range = {best_tight, best_wide, *best_interior}
    if best_model is not None:
        by_range.add(best_model)
    by_behind = set(best_behind)

    if len(by_range | by_behind) == 1:
        stable = (
            f"вердикт «{best_tight}» не меняется ни на одной ширине модели диапазона"
            + (", ни если живые за героем тоже войдут в банк" if by_behind else "")
            + " — допущение на него не влияет"
        )
        return Zone.STRICT, stable
    if len(by_range) == 1 and by_behind - by_range:
        moved = ", ".join(sorted(by_behind - by_range))
        return Zone.ASSUMING, (
            f"вердикт «{best_tight}» держится на том, что живые позади не войдут в "
            f"банк: если войдут, лучше «{moved}»"
        )
    if best_model is not None and best_model not in {best_tight, best_wide, *best_interior}:
        return Zone.ASSUMING, (
            f"вердикт «{best_model}» держится на модели диапазона: ни одна ширина "
            f"вилки его не подтверждает"
        )
    if best_tight == best_wide and len(by_range) > 1:
        return Zone.ASSUMING, (
            f"на концах интервала вердикт «{best_tight}», но внутри него он "
            f"переворачивается — устойчивым он не является"
        )
    return Zone.ASSUMING, (
        f"вердикт зависит от модели диапазона: на узком конце лучше «{best_tight}», "
        f"на широком — «{best_wide}»"
    )


def _hero_class(hand: CanonicalHand) -> str | None:
    """Класс карманных карт героя. Вскрытие не читаем — только раздачу."""
    cards = hand.dealt.get(hand.hero_label, [])
    if len(cards) != 2:
        return None
    return class_of(*cards)


def _unjudged(
    dp: DecisionPoint,
    spot: SpotKind,
    reason: str,
    detail: Mapping[str, object] | None = None,
) -> PointVerdict:
    """Точка без вердикта: спот размечен, цена не посчитана.

    Признак «вердикта нет» — пустой `best_action`; на такие точки не ссылается
    ранжирование и не опирается изложение. Зона здесь `strict` не потому, что
    вывод точен, а потому, что вывода нет вовсе: допущение не сделано, и
    инвариант «assumption заполнено тогда и только тогда, когда зона assuming»
    обязан выполняться и на таких точках.

    `detail` — то, что успело посчитаться до отказа. Оно остаётся в вердикте
    ради разбора и будущего интервала вместо точки, но игроку не показывается
    ничем: и ранжирование, и сводка смотрят на `best_action`
    (`error_cost.is_judged`), а `ev_diff_bb` здесь ноль.
    """
    return PointVerdict(
        dp_index=dp.index,
        street=dp.street,
        spot=spot,
        zone=Zone.STRICT,
        action_taken=action_name(dp),
        best_action="",
        ev_diff_bb=0.0,
        assumption=None,
        tools=[],
        detail={**(detail or {}), "unjudged": reason},
    )


def _shover(state: TableState) -> SeatSnapshot | None:
    """Кто поставил перед героем ставку, которую тот коллирует или сбрасывает."""
    if state.aggressor is not None and state.aggressor.live:
        return state.aggressor
    rivals = [s for s in state.seats if s.live and s.acted and s.label != state.hero.label]
    if not rivals:
        return None
    return max(rivals, key=lambda s: (s.street_committed, s.label))


def _shove_action_index(hand: CanonicalHand, dp: DecisionPoint, shover: SeatSnapshot) -> int:
    """Номер последнего действия шовера в руке до решения героя.

    Запасной вариант (шовер до решения героя не ходил вовсе) — номер самого
    решения героя: лучшего восстановления из этих данных не получить.
    """
    target = action_index(hand, dp)
    return next(
        (i for i in range(target - 1, -1, -1) if hand.actions[i].label == shover.label), target
    )


def _rivals_when_shoved(
    hand: CanonicalHand, dp: DecisionPoint, state: TableState, shover: SeatSnapshot
) -> list[SeatSnapshot]:
    """Кто мог ответить на шов: состав стола на момент ХОДА ШОВЕРА, без него самого.

    `state` — снимок на момент решения ГЕРОЯ, и прочитать состав из него нельзя
    ни одним из двух очевидных способов. Все места подряд — слишком много:
    сбросивший карты ДО шова заколлировать его не мог, и в цену шова его стек не
    входил (так и было, и на этом ломалось). Живые в снимке — слишком мало:
    между шовом и ходом героя карты успевают сбросить те, кто для шовера был
    жив, а их стеки цену его шова ограничивали. Поэтому состав восстанавливается
    по действиям руки до хода шовера.

    Игрок, чьё действие ДО шова оставило его без фишек, не входит. Число, ради
    которого этот состав считается, — глубина, по которой шоверу приписывается
    диапазон шова, а диапазон шова осмыслен ровно постольку, поскольку у кого-то
    есть выбор «коллировать или пас». У игрока без фишек за спиной выбора нет: он
    не даёт шоверу ни фолд-эквити, ни диапазона колла. Правило закреплено по
    составу, а не по числу.

    Место, вычеркнутое движком из руки (`state.forfeits`), не входит тоже:
    закреплено `test_a_forfeited_seat_could_not_have_answered_the_shove`.

    Остальные два свойства закреплены:
    `test_shover_depth_counts_only_those_live_when_he_shoved` проверяет число,
    `test_shover_depth_ignores_a_player_already_all_in_when_the_shove_landed`
    — состав.
    """
    shove_at = _shove_action_index(hand, dp, shover)
    gone = {
        action.label
        for action in hand.actions[:shove_at]
        if action.kind is ActionKind.FOLD or action.is_all_in
    }
    gone |= state.forfeits
    return [seat for seat in state.seats if seat.label != shover.label and seat.label not in gone]


def _posted_before_shove(hand: CanonicalHand, dp: DecisionPoint, shover: SeatSnapshot) -> int:
    """Сколько шовер вложил в банк ДО собственного шова, в фишках.

    `SeatSnapshot.contributed` снят на решении героя и сам шов уже содержит, а
    подыгра, которую решает `_shover_equilibrium`, начинается перед ним. Если до
    шова шовер уже действовал, берётся накопленное тем действием; иначе —
    вынужденная ставка его позиции, той же формулой `forced_blind`, которой
    считает посты движок. Закреплено
    `test_the_shover_subgame_starts_before_his_own_shove`.
    """
    shove_at = _shove_action_index(hand, dp, shover)
    earlier = [a.committed_after for a in hand.actions[:shove_at] if a.label == shover.label]
    if earlier:
        return shover.ante + earlier[-1]
    player = next(p for p in hand.players if p.label == shover.label)
    return shover.ante + forced_blind(hand, player, shover.ante)


def _shover_equilibrium(
    state: TableState,
    shover: SeatSnapshot,
    shover_posted: int,
    rivals: Sequence[SeatSnapshot],
    bb: int,
) -> MultiwaySolution:
    """Равновесие подыгры, в которую играл ШОВЕР: его шов против всех, кто был позади.

    Деньги берутся на момент его хода: банк без самого шова и вклад шовера без
    него же. Вклады и остатки остальных мест берутся из снимка на решении героя
    — состав `rivals` восстановлен `_rivals_when_shoved`.

    Потолок вкладов — стек ШОВЕРА: больше, чем покрыл он сам, из чужих стеков в
    его банк не входит. Это тот же потолок, по которому `_unopened_verdict`
    считает банк своему герою.

    Возвращается связка целиком: пуш-сторона — диапазон, который приписывается
    шоверу, колл-стороны — диапазоны тех, кто на этот шов отвечал (герой в их
    числе). Разрывать пару нельзя: колл-сторона является наилучшим ответом на
    шов ТОГО ЖЕ решения — закреплено
    `test_the_call_range_answers_the_shove_range_of_the_same_solution`.

    При одном игроке позади шовера пуш-сторона обязана совпасть с `nash_hu`
    поклассно: `test_the_shover_range_with_one_player_behind_is_the_nash_push_range`.
    """
    ceiling = shover.stack
    pot_dead = sum(
        min(shover_posted if seat.label == shover.label else seat.contributed, ceiling)
        for seat in state.seats
    )
    return unopened_shove_equilibrium(
        MultiwaySeat(posted_bb=shover_posted / bb, behind_bb=(shover.stack - shover_posted) / bb),
        [
            MultiwaySeat(posted_bb=min(seat.contributed, ceiling) / bb, behind_bb=seat.behind / bb)
            for seat in rivals
        ],
        pot_dead / bb,
    )


def _nothing_dead_besides(state: TableState, opponent: SeatSnapshot) -> bool:
    """Вынужденную ставку сделал герой, и никто, кроме него и названного места.

    Проверяются два условия: вклад героя больше его анте, а вклад каждого
    остального места, кроме названного, своему анте равен. Тогда всё, что лежит
    в банке сверх анте стола (`_table_dead_bb`), внесли ровно эти двое.

    Гейт равновесия читает результат в `_unopened_verdict`, `cheap_fold_verdict`
    и `_facing_shove_verdict`. Закреплено тремя тестами:
    `test_a_forfeited_small_blind_does_not_open_the_heads_up_equilibrium`
    (чужая вынужденная ставка в банке),
    `test_an_ante_only_forfeit_does_not_open_the_heads_up_equilibrium`
    (вынужденной ставки не делал сам герой),
    `test_a_dead_small_blind_is_not_the_heads_up_equilibrium_against_a_shove`
    (то же против шова).
    """
    return state.hero.contributed > state.hero.ante and all(
        seat.contributed == seat.ante
        for seat in state.seats
        if seat.label not in (state.hero.label, opponent.label)
    )


def _unopened_verdict(dp: DecisionPoint, en: EnrichedHand, state: TableState) -> PointVerdict:
    """Шов или фолд в неоткрытый банк."""
    spot = SpotKind.PUSHFOLD_UNOPENED
    hero_cls = _hero_class(en.hand)
    if hero_cls is None:
        return _unjudged(dp, spot, "карты героя неизвестны")

    bb = en.hand.bb
    ceiling = state.hero.stack
    behind = [s for s in state.behind_hero if s.behind > 0]
    all_in_behind = len(state.behind_hero) - len(behind)
    if all_in_behind:
        return _unjudged(
            dp,
            spot,
            f"в руке живых без фишек за спиной помимо героя — {all_in_behind}: "
            f"перебор подмножеств коллеров их не берёт, и цена шова посчитана "
            f"против неполного состава",
        )
    if not behind:
        return _unjudged(dp, spot, "позади героя некому коллировать")
    if len(behind) > _MAX_MODELLED_CALLERS:
        return _unjudged(dp, spot, f"игроков позади {len(behind)} — перебор подмножеств ограничен")
    if state.hero.behind <= 0:
        return _unjudged(dp, spot, "у героя не осталось фишек за спиной")

    hero_behind_bb = state.hero.behind / bb
    hero_posted_bb = state.hero.contributed / bb
    pot_dead_bb = state.pot_before / bb
    dead_bb = _table_dead_bb(state)
    # Глубина равновесия — стек ПОСЛЕ анте: само анте входит в игру отдельным
    # слагаемым мёртвых денег, и складывать его в стек значило бы посчитать дважды.
    hero_eff = state.hero.stack_after_ante
    depths = [min(hero_eff, seat.stack_after_ante) / bb for seat in behind]

    def callers(ranges: Sequence[Range]) -> list[CallerModel]:
        return [
            CallerModel(
                call_range=rng,
                behind_bb=seat.behind / bb,
                posted_bb=min(seat.contributed, ceiling) / bb,
            )
            for seat, rng in zip(behind, ranges, strict=True)
        ]

    def ev(ranges: Sequence[Range]) -> float:
        return _shove_ev_bb(
            hero_cls,
            hero_behind_bb,
            pot_dead_bb,
            callers(ranges),
            hero_posted_bb=hero_posted_bb,
            equity_fn=_model_equity,
        )

    try:
        solution = _table_equilibrium(state, behind, bb)
    except DidNotConverge as failure:
        return _unjudged(dp, spot, _NO_EQUILIBRIUM, {"solver_error": str(failure)})
    model_ranges = list(solution.calls)
    model_callers = callers(model_ranges)
    # Контрольная сумма модели стола. Считается здесь, на тех же `CallerModel`,
    # что уходят в `shove_ev_bb`, а решение по ней принимается перед выдачей
    # вердикта — вместе с проверкой вилки и в этом порядке (сначала модель,
    # потом устойчивость): числа расчёта остаются в `detail` снятой точки, по
    # ним видно, чем именно она снята.
    broken_model = _model_checksum(model_callers, hero_cls)
    ev_model = ev(model_ranges)
    # Опрашивается вся сетка множителей, а не два конца полосы: EV по ширине не
    # монотонна, и вердикт умеет перевернуться внутри интервала. Множитель
    # применяется к СВОЕЙ равновесной ширине каждого места (места отличаются
    # постами, и равновесные ширины у них разные), а порядок классов — по эквити
    # против равновесного шова героя: коллер отвечает именно на этот шов.
    order = classes_by_equity_against(solution.push)
    equilibrium_widths = [rng.fraction_of_hands() for rng in model_ranges]
    ev_by_width = {
        _WIDTH_KEY(multiplier): ev(
            [
                range_of_width_in_order(order, min(1.0, width * multiplier))
                for width in equilibrium_widths
            ]
        )
        for multiplier in _SHOVE_CALL_WIDTH_MULTIPLIERS
    }
    ev_tight = ev_by_width[_WIDTH_KEY(_SHOVE_CALL_WIDTH_MULTIPLIERS[0])]
    ev_wide = ev_by_width[_WIDTH_KEY(_SHOVE_CALL_WIDTH_MULTIPLIERS[-1])]

    equilibrium_depth = None
    if (
        state.live_total == 2
        and len(behind) == 1
        and behind[0].position == "BB"
        and _nothing_dead_besides(state, behind[0])
    ):
        equilibrium_depth = _equilibrium_depth(min(hero_eff, behind[0].stack_after_ante) / bb)

    by_width = [_best_of("shove", value) for value in ev_by_width.values()]
    best_tight, best_wide = by_width[0], by_width[-1]
    best = _best_of("shove", ev_model)
    bracket_shove = "stable" if {*by_width, best} == {best} else "unstable"
    # Вторая ось (входят ли живые позади) здесь уже внутри модели: перебор
    # подмножеств интегрирует их поведение с вероятностями, а сетка ширин двигает
    # сами вероятности от «коллирует каждый пятый» до «коллируют все». Отдельного
    # конца добавлять нечего — кроме случая, когда живой игрок позади в перебор не
    # попал вовсе. Тогда измерение вне модели, и решает это `zone_for`.
    zone, why = zone_for(
        best_tight,
        best_wide,
        live_total=state.live_total,
        equilibrium=equilibrium_depth is not None,
        best_model=best,
        best_interior=by_width[1:-1],
    )
    taken = "shove" if state.hero_all_in_after else "fold"
    folds_possible = fold_equity_ok(callers(model_ranges))

    detail: dict[str, object] = {
        "method": "subset_enumeration",
        "bracket": bracket_shove,
        "branches": 2 ** len(behind),
        "fold_equity_ok": folds_possible,
        "ev_shove_bb": round(ev_model, 4),
        "ev_shove_tight_bb": round(ev_tight, 4),
        "ev_shove_wide_bb": round(ev_wide, 4),
        "ev_shove_by_width_bb": {w: round(v, 4) for w, v in ev_by_width.items()},
        "hero_class": hero_cls,
        "depths_bb": [round(_depth_key(depth), 2) for depth in depths],
        "dead_extra_bb": round(dead_bb, 4),
        "zone_reason": why,
        "model_within_bracket": best in set(by_width),
        "shove_range_fraction": round(solution.push.fraction_of_hands(), 6),
        "call_range_fractions": [round(rng.fraction_of_hands(), 6) for rng in model_ranges],
        "equilibrium_hand_regret_bb": round(solution.hand_regret_bb, 6),
        **_checksum_detail(model_callers, hero_cls),
    }
    if broken_model:
        return _unjudged(dp, spot, broken_model, detail)
    # Интервал по обе стороны нуля точечной оценки не даёт, но и отказом больше
    # не является: точка получает вердикт «около нуля» (`_BOTH_ACCEPTABLE`) с
    # интервалом и потолком цены. Форма, где колл-диапазон взят из равновесия, а
    # не угадан, — исключение: там вердикт держит равновесие, а не интервал.
    near_zero = bracket_shove == "unstable" and equilibrium_depth is None
    interval = _interval_of([ev_model, *ev_by_width.values()], ev_model, near_zero)
    return PointVerdict(
        dp_index=dp.index,
        street=dp.street,
        spot=spot,
        zone=zone,
        action_taken=taken,
        best_action=_BOTH_ACCEPTABLE if near_zero else best,
        interval=interval,
        # Цена точки «около нуля» — ноль: оба варианта допустимы, и упрекать
        # игрока за выбранный не за что. Правило то же, что у развилки по второй
        # оси (`_BEST_DEPENDS_ON_BEHIND`), и оно же не даёт такой точке попасть
        # в список расхождений сводки.
        ev_diff_bb=(
            0.0
            if near_zero
            else round(_taken_ev(taken, "shove", ev_model) - max(ev_model, 0.0), 6)
        ),
        assumption=(
            Assumption(
                range=_average_range(model_ranges),
                source="model:multiway_pushfold",
                note=_ASSUMPTION_CALLERS,
            )
            if zone is Zone.ASSUMING
            else None
        ),
        tools=["multiway_pushfold", "shove_ev_bb", "fold_equity_ok"],
        detail=detail,
    )


def _facing_shove_verdict(dp: DecisionPoint, en: EnrichedHand, state: TableState) -> PointVerdict:
    """Колл или фолд против ставки, которая доводит героя до олл-ина."""
    spot = SpotKind.PUSHFOLD_FACING_SHOVE
    hero_cls = _hero_class(en.hand)
    if hero_cls is None:
        return _unjudged(dp, spot, "карты героя неизвестны")

    shover = _shover(state)
    if shover is None:
        return _unjudged(dp, spot, "не удалось определить, кто поставил")
    bb = en.hand.bb
    if state.to_call <= 0 or state.hero.behind <= 0:
        return _unjudged(dp, spot, "доплаты нет либо у героя не осталось фишек")

    # Живой без фишек за спиной (`behind == 0`) в модельный набор коллеров не
    # входит: ось «войдёт или нет» для него пуста. Посчитать точку при этом
    # нечем — `call_shove_ev_bb` берёт эквити против ОДНОГО диапазона и весь
    # `pot_before` записывает герою, — поэтому вердикта здесь нет, как и у спота
    # с уже ответившим на шов. Закреплено
    # `test_a_blind_all_in_behind_hero_is_not_priced`.
    live_behind = [
        seat
        for seat in state.seats
        if seat.live and seat.label not in (state.hero.label, shover.label)
    ]
    behind = [seat for seat in live_behind if seat.behind > 0]
    all_in_behind = len(live_behind) - len(behind)
    if all_in_behind:
        return _unjudged(
            dp,
            spot,
            f"в руке живых без фишек за спиной помимо героя и шовера — "
            f"{all_in_behind}: во вскрытии больше двух участников, а эквити "
            f"считается против одного диапазона",
        )

    dead_bb = _table_dead_bb(state)
    rivals = _rivals_when_shoved(en.hand, dp, state, shover)
    if not rivals:
        return _unjudged(dp, spot, "на момент шова отвечать на него было некому")
    if len(rivals) > _MAX_MODELLED_CALLERS:
        return _unjudged(
            dp,
            spot,
            f"на момент шова позади шовера было {len(rivals)} игроков — больше, чем "
            f"решатель равновесия берёт, и приписать шоверу диапазон не из чего",
        )
    if any(seat.behind <= 0 for seat in rivals):
        return _unjudged(
            dp,
            spot,
            "на момент шова позади шовера было место без фишек за спиной: выбора "
            "«коллировать или пас» у него не было, а равновесие решается для стола, "
            "где он есть у каждого",
        )
    shover_posted = _posted_before_shove(en.hand, dp, shover)
    if shover.stack <= shover_posted:
        return _unjudged(dp, spot, "у шовера не было фишек за спиной — шовить ему было нечем")
    try:
        solution = _shover_equilibrium(state, shover, shover_posted, rivals, bb)
    except DidNotConverge as failure:
        return _unjudged(dp, spot, _NO_EQUILIBRIUM, {"solver_error": str(failure)})

    shover_depth_bb = (
        min(shover.stack_after_ante, max(seat.stack_after_ante for seat in rivals)) / bb
    )
    pot_bb = state.pot_before / bb
    to_call_bb = state.to_call / bb
    hero_bb = state.hero.behind / bb

    def ev(rng: Range) -> float:
        return call_shove_ev_bb(
            hero_cls, hero_bb, rng, pot_bb, to_call_bb, equity_fn=_model_equity
        )

    # Диапазон шова — пуш-сторона равновесия ЕГО стола, а не хедз-ап равновесия
    # его глубины: у шовера была своя позиция и своё число игроков позади, и
    # хедз-ап пуш-диапазон отвечает на другую игру.
    model_range = solution.push
    ev_model = ev(model_range)
    width_ranges = {
        width: range_of_width(_depth_key(shover_depth_bb), width, dead_extra_bb=dead_bb)
        for width in _SHOVER_RANGE_WIDTHS
    }
    ev_by_width = {width: ev(rng) for width, rng in width_ranges.items()}
    ev_tight = ev_by_width[_SHOVER_RANGE_WIDTHS[0]]
    ev_wide = ev_by_width[_SHOVER_RANGE_WIDTHS[-1]]

    # Вторая ось вилки: живые за героем. `call_shove_ev_bb` считает вскрытие один
    # на один, поэтому их возможный вход в банк — величина, которой в модели нет
    # вовсе. Считаем противоположный конец: все они коллируют. Эквити героя тогда
    # делится на всех (хуже для него), но и банк растёт на их деньги (лучше), —
    # обе поправки берутся вместе, иначе конец вилки был бы искусственно мрачным.
    # Арифметика та же самая, из замороженного инструмента: подменяется только
    # набор диапазонов на вскрытии и размер банка.
    behind_unmodelled = len(behind) > _MAX_MODELLED_CALLERS
    best_behind: list[str] = []
    ev_behind: float | None = None
    behind_ranges: list[Range] = []
    if behind and not behind_unmodelled:
        # Колл-диапазоны берутся из ТОГО ЖЕ решения, что и диапазон шова: эти
        # игроки отвечали на этот самый шов. Каждый из них есть среди `rivals`
        # (живой на решении героя не выбыл до шова) — закреплено
        # `test_players_behind_hero_answer_the_same_shove_as_hero`.
        rival_at = {seat.label: index for index, seat in enumerate(rivals)}
        behind_ranges = [solution.calls[rival_at[seat.label]] for seat in behind]
        pot_with_behind_bb = (state.pot_before + _extra_from_behind(state, behind)) / bb

        def ev_all(rng: Range) -> float:
            return call_shove_ev_bb(
                hero_cls,
                hero_bb,
                rng,
                pot_with_behind_bb,
                to_call_bb,
                equity_fn=_equity_with_behind(behind_ranges),
            )

        ev_behind = ev_all(model_range)
        ev_behind_by_width = {width: ev_all(rng) for width, rng in width_ranges.items()}
        best_behind = [_best_of("call", ev_behind), *(
            _best_of("call", value) for value in ev_behind_by_width.values()
        )]

    equilibrium_depth = None
    if (
        state.live_total == 2
        and state.hero.position == "BB"
        and shover.position in ("SB", "BTN")
        and state.voluntary_actors == (shover.label,)
        and _nothing_dead_besides(state, shover)
    ):
        equilibrium_depth = _equilibrium_depth(
            min(state.hero.stack_after_ante, shover.stack_after_ante) / bb
        )

    by_width = [_best_of("call", value) for value in ev_by_width.values()]
    best_tight, best_wide = by_width[0], by_width[-1]
    best = _best_of("call", ev_model)
    # Две оси разводятся в `detail` намеренно: они отвечают на разные вопросы —
    # «зависит ли вывод от угаданного диапазона» и «зависит ли он от того, войдут
    # ли живые позади». Слепить их в один флаг значило бы лишить изложение
    # возможности назвать причину.
    bracket_call = "stable" if {*by_width, best} == {best} else "unstable"
    # «Ось сдвинула вердикт» — значит расчёт с вошедшими в банк игроками позади
    # даёт не то, что выдала модель. Сравнивать надо именно с вердиктом модели, а
    # не с объединением концов вилки: иначе ось молчала бы всякий раз, когда
    # диапазонная вилка и так неустойчива, то есть ровно там, где смотреть на неё
    # интереснее всего.
    behind_moved = bool(set(best_behind) - {best})
    behind_axis = None if not best_behind else ("unstable" if behind_moved else "stable")
    best_all_behind = None if ev_behind is None else _best_of("call", ev_behind)
    verdict_splits = best_all_behind is not None and best_all_behind != best
    zone, why = zone_for(
        best_tight,
        best_wide,
        live_total=state.live_total,
        equilibrium=equilibrium_depth is not None,
        best_model=best,
        best_interior=by_width[1:-1],
        best_behind=best_behind,
        unmodelled=(
            f"живых за героем {len(behind)} — больше, чем модель вскрытия способна "
            f"перебрать, их влияние на вердикт не проверено"
            if behind_unmodelled
            else ""
        ),
    )
    taken = "call" if dp.action.kind is ActionKind.CALL else "fold"

    detail: dict[str, object] = {
        "method": "call_ev",
        "bracket": bracket_call,
        "ev_call_bb": round(ev_model, 4),
        "ev_call_tight_bb": round(ev_tight, 4),
        "ev_call_wide_bb": round(ev_wide, 4),
        "ev_call_by_width_bb": {str(w): round(v, 4) for w, v in ev_by_width.items()},
        "hero_class": hero_cls,
        "required_equity": round(required_equity(state.to_call, state.pot_before), 6),
        "shover_depth_bb": round(_depth_key(shover_depth_bb), 2),
        "dead_extra_bb": round(dead_bb, 4),
        # Сколько живых за героем модель перебирает как возможных коллеров. Уже
        # ответивший на шов сюда попасть не может: такой спот `spot_for` до этой
        # функции не допускает — см. `test_a_player_who_already_called_the_shove_is_not_priced`.
        "live_others": len(behind),
        "behind_axis": behind_axis,
        "rivals_when_shoved": len(rivals),
        "shove_range_fraction": round(model_range.fraction_of_hands(), 6),
        "call_range_fractions": [round(rng.fraction_of_hands(), 6) for rng in behind_ranges],
        "equilibrium_hand_regret_bb": round(solution.hand_regret_bb, 6),
        # Обе точки модели по отдельности: против одного диапазона и с вошедшими
        # в банк живыми позади. Когда они расходятся, `best_action` называет
        # развилку, а не одно из этих действий.
        "best_vs_one": best,
        "best_all_behind": best_all_behind,
        "ev_call_all_behind_bb": None if ev_behind is None else round(ev_behind, 4),
        "zone_reason": why,
    }
    # То же правило, что и для шова в неоткрытый банк: интервал по обе стороны
    # нуля даёт вердикт «около нуля», а не отказ. Интервал считается по ОДНОЙ
    # оси — моделям диапазона шовера; вторая ось (войдут ли живые позади) в него
    # не входит и работает как прежде: она двигает зону и снимает упрёк.
    near_zero = bracket_call == "unstable" and equilibrium_depth is None
    interval = _interval_of([ev_model, *ev_by_width.values()], ev_model, near_zero)
    return PointVerdict(
        dp_index=dp.index,
        street=dp.street,
        spot=spot,
        zone=zone,
        action_taken=taken,
        best_action=(
            _BOTH_ACCEPTABLE
            if near_zero
            else (_BEST_DEPENDS_ON_BEHIND if verdict_splits else best)
        ),
        interval=interval,
        # Цена берётся по самому мягкому упрёку среди сценариев второй оси.
        # Обвинять игрока в потере 0.72bb за пас, когда собственный расчёт при
        # входе живого позади даёт -2.00bb, нельзя: это число ведёт и
        # ранжирование, и сумму потерь руки. Ярлык `assuming` предупреждает о
        # природе вывода, но не отменяет самого числа, а цифру игрок читает
        # первой. Сетка ширин диапазона в цену НЕ входит: там завышение
        # объявлено известным свойством модели и покрыто ярлыком зоны.
        ev_diff_bb=(
            0.0
            if near_zero
            else round(
                max(
                    _taken_ev(taken, "call", value) - max(value, 0.0)
                    for value in ([ev_model] if ev_behind is None else [ev_model, ev_behind])
                ),
                6,
            )
        ),
        assumption=(
            Assumption(
                range=model_range,
                source="model:multiway_pushfold",
                note=_ASSUMPTION_SHOVER
                + (
                    f"; вдобавок вердикт двигают {len(behind)} живых позади — "
                    f"если они тоже войдут в банк, лучше сыграть иначе"
                    if behind_moved
                    else ""
                ),
            )
            if zone is Zone.ASSUMING
            else None
        ),
        tools=["multiway_pushfold", "call_shove_ev_bb", "required_equity"],
        detail=detail,
    )


def _extra_from_behind(state: TableState, behind: Sequence[SeatSnapshot]) -> int:
    """Сколько фишек добавят в банк героя живые позади, если тоже заколлируют.

    Каждый доколлирует до уровня ставки, но не больше своего стека; из этого
    герой способен выиграть лишь то, что покрыто его собственным вкладом, —
    потолок тот же, по которому движок считает `pot_before`.
    """
    ceiling = state.hero.stack
    level = max(seat.street_committed for seat in state.seats)
    total = 0
    for seat in behind:
        final = min(seat.stack, seat.ante + level)
        total += max(min(final, ceiling) - min(seat.contributed, ceiling), 0)
    return total


def _equity_with_behind(behind_ranges: Sequence[Range]) -> Callable[..., float]:
    """Эквити героя на вскрытии, куда добавлены диапазоны живых позади.

    Подменяет только эквити: сама арифметика банка остаётся в `call_shove_ev_bb`,
    иначе формулу денег пришлось бы написать второй раз — ровно тот дубль, на
    котором этот проект уже ловил расхождение.
    """

    def fn(hero: _HeroCombo, ranges: Sequence[Range]) -> float:
        return _model_equity(hero, [*ranges, *behind_ranges])

    return fn


def _interval_of(values: Sequence[float], point: float, near_zero: bool) -> EvInterval:
    """Интервал EV по моделям диапазона: концы — размах, точка — сама модель.

    В размах входит и `point`: модель диапазона задана дробными весами, а не
    шириной, поэтому её EV может лежать вне значений сетки ширин — и точка,
    выпавшая из собственного интервала, была бы посчитана не по тому набору
    (инвариант проверяет `EvInterval`).
    """
    return EvInterval(
        point_bb=round(point, 6),
        low_bb=round(min(values), 6),
        high_bb=round(max(values), 6),
        near_zero=near_zero,
    )


def _best_of(active: str, ev: float) -> str:
    """Лучшее из двух действий: активное при плюсовой EV, иначе фолд (фолд = 0)."""
    return active if ev > 0.0 else "fold"


def _taken_ev(taken: str, active: str, ev: float) -> float:
    return ev if taken == active else 0.0


# Порог дешёвого префильтра (задача 13, SCALING.md §3): доля веса шова в
# равновесном чарте на САМОЙ КОРОТКОЙ глубине среди живых позади героя — той,
# что даёт равновесию САМЫЙ ШИРОКИЙ шов (короче эффективный стек — шире шов,
# см. замер в комментарии к `_DEPTH_STEP_BB`: 72o/32o/83o на 10.25bb с тремя
# позади дают ПОЛОЖИТЕЛЬНУЮ EV шова именно за счёт фолд-эквити более узкого
# поля). Если даже на этой, самой щедрой к шову глубине чарт не даёт классу
# героя веса больше десятой доли, дальше можно не считать: полный перебор
# подмножеств с сеткой ширин колл-диапазона (`_unopened_verdict`) способен
# только СУЗИТЬ обоснование шова относительно этой оценки — больше живых
# позади означает больше шансов быть отвеченным, а не меньше, — и развернуть
# вердикт в сторону шова он не может. Порог найден не подбором: 0.1 — это то
# же число, которым отсекается сама сводка скана (задача 13, `< -0.1bb`), и
# смысл тот же: цена ошибки ниже него всё равно не попала бы в список.
_PREFILTER_PUSH_WEIGHT_MAX = 0.1


def cheap_fold_verdict(dp: DecisionPoint, en: EnrichedHand) -> PointVerdict | None:
    """Дешёвый вердикт «фолд верен» для тривиального неоткрытого фолда — рычаг скана.

    Не альтернатива `verdict_for`, а обгон перед ним. Большинство рук турнирного
    файла — «сфолдил в неоткрытый банк, отдал блайнды» (SCALING.md §3), и для
    них дорогая часть расчёта (`shove_ev_bb`: перебор 2^n подмножеств коллеров
    на КАЖДОЙ из точек сетки ширин, с Монте-Карло на мультивее) ничего не меняет
    в выводе — чарт уже уверенно говорит «фолд». Эта функция закрывает именно
    такую точку одним попаданием в закешированный равновесный push-чарт
    (`_push_model`, тот же самый, которым уже пользуется `_unopened_verdict`),
    без единого вызова эквити-инструментов.

    Возвращает `None`, если условия не выполняются или чарт не даёт уверенного
    «фолд» (весом >= 0.9) — тогда точку обязан посчитать `verdict_for` целиком:
    отказ здесь не констатирует ошибку, а лишь снимает с себя право её судить
    дёшево. Это гарантирует отсутствие ложных «расхождения нет» на настоящих
    промахах: см. `_PREFILTER_PUSH_WEIGHT_MAX`.

    Дешёвый лукап не имеет права быть увереннее полного расчёта, поэтому оба
    его правила действуют и здесь. Контрольную сумму модели (`_model_checksum`)
    он считает сам — она не требует эквити и снимает точку прямо тут, без
    дорогого перебора. Интервал EV по ширинам колл-диапазона он не считает
    вовсе, а именно знак этого интервала решает, будет ли у точки точечная
    оценка или форма «около нуля»: поэтому мультивей уходит на полный расчёт, а
    лукап закрывает только форму, где колл-диапазон взят из равновесия (SB
    против BB один на один) — там вердикт держит равновесие. Отсюда зона
    `strict` без допущения: вывода на догадке эта функция больше не производит.
    """
    if dp.street is not Street.PREFLOP or dp.action.kind is not ActionKind.FOLD:
        return None
    state = table_state(dp, en)
    if spot_for(dp, state) is not SpotKind.PUSHFOLD_UNOPENED:
        return None

    hero_cls = _hero_class(en.hand)
    if hero_cls is None:
        return None
    behind_all = state.behind_hero
    behind = [s for s in behind_all if s.behind > 0]
    if len(behind) != len(behind_all):
        # Живой олл-ин позади (короткий блайнд ушёл в олл-ин постом) — вне
        # модели шова: в `_unopened_verdict` такая точка остаётся без вердикта.
        # Дешёвый лукап её не разбирает — она уходит на полный расчёт, который
        # знает, что с ней делать.
        return None
    if not behind or state.hero.behind <= 0:
        return None
    if len(behind) > _MAX_MODELLED_CALLERS:
        # Перебор подмножеств в `_unopened_verdict` на таком числе коллеров сам
        # не считается (2^n веток) и возвращает точку БЕЗ вердикта — дешёвый
        # лукап не имеет права быть увереннее полного расчёта там, где тот
        # прямо отказывается судить.
        return None

    bb = en.hand.bb
    hero_eff = state.hero.stack_after_ante
    depths = [min(hero_eff, seat.stack_after_ante) / bb for seat in behind]
    dead_bb = _table_dead_bb(state)
    shortest_depth = min(depths)
    push_range = _push_model(shortest_depth, dead_bb)
    push_weight = push_range.weight(hero_cls)
    if push_weight > _PREFILTER_PUSH_WEIGHT_MAX:
        return None

    equilibrium_depth = None
    if (
        state.live_total == 2
        and len(behind) == 1
        and behind[0].position == "BB"
        and _nothing_dead_besides(state, behind[0])
    ):
        equilibrium_depth = _equilibrium_depth(min(hero_eff, behind[0].stack_after_ante) / bb)

    # Те же два правила, что и у полного расчёта, — иначе дешёвый лукап был бы
    # увереннее его. Контрольная сумма считается по ТОМУ ЖЕ равновесию стола,
    # что и в `_unopened_verdict`: две разные модели коллеров снимали бы с точки
    # вердикт по разным причинам, и лукап отвергал бы то, что полный расчёт
    # судит. Решение точки считается один раз на обоих путях — его запоминает
    # сам решатель.
    try:
        solution = _table_equilibrium(state, behind, bb)
    except DidNotConverge:
        return None  # отказ формулирует полный расчёт, а не лукап
    model_callers = [
        CallerModel(
            call_range=call_range,
            behind_bb=seat.behind / bb,
            posted_bb=min(seat.contributed, state.hero.stack) / bb,
        )
        for seat, call_range in zip(behind, solution.calls, strict=True)
    ]
    broken_model = _model_checksum(model_callers, hero_cls)
    if broken_model:
        return _unjudged(
            dp,
            SpotKind.PUSHFOLD_UNOPENED,
            broken_model,
            {
                "method": "prefilter_chart_lookup",
                "hero_class": hero_cls,
                "depths_bb": [round(_depth_key(depth), 2) for depth in depths],
                "dead_extra_bb": round(dead_bb, 4),
                **_checksum_detail(model_callers, hero_cls),
            },
        )
    # Интервал EV по ширинам колл-диапазона лукап не считает вовсе, а именно его
    # знак решает, получит точка точечную оценку или форму «около нуля».
    # Заявить его здесь нечем, поэтому мультивей уходит на полный расчёт: он
    # интервал считает. Форма с равновесным колл-диапазоном остаётся за лукапом
    # — там вердикт держит равновесие.
    if equilibrium_depth is None:
        return None

    detail: dict[str, object] = {
        "method": "prefilter_chart_lookup",
        "hero_class": hero_cls,
        "push_weight": round(push_weight, 6),
        "lookup_depth_bb": round(shortest_depth, 2),
        "dead_extra_bb": round(dead_bb, 4),
        "zone_reason": "хедз-ап SB против BB: колл-диапазон взят из равновесия пуш-фолда",
    }
    return PointVerdict(
        dp_index=dp.index,
        street=dp.street,
        spot=SpotKind.PUSHFOLD_UNOPENED,
        zone=Zone.STRICT,
        action_taken="fold",
        best_action="fold",
        ev_diff_bb=0.0,
        assumption=None,
        tools=["nash_hu"],
        detail=detail,
    )


def verdict_for(dp: DecisionPoint, en: EnrichedHand) -> PointVerdict:
    """Вердикт по одной точке решения героя.

    Постфлоп и прочий префлоп в v1 не оцениваются и возвращаются без вердикта:
    инструмента, который посчитал бы их цену, у нас пока нет, а назвать
    неизвестную цену нулём и промолчать — значит выдать пробел за отсутствие
    ошибки.
    """
    if dp.street is not Street.PREFLOP:
        return _unjudged(dp, SpotKind.POSTFLOP, "постфлоп в v1 не оценивается")

    state = table_state(dp, en)
    spot = spot_for(dp, state)
    if spot is SpotKind.PUSHFOLD_UNOPENED:
        return _unopened_verdict(dp, en, state)
    if spot is SpotKind.PUSHFOLD_FACING_SHOVE:
        return _facing_shove_verdict(dp, en, state)
    return _unjudged(dp, spot, unpriced_reason(dp, state))
