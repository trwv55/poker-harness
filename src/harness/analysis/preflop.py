"""Вердикт по префлоп-точке пуш-фолд-зоны: EV решения, зона доверия, цена.

Всё считается **против диапазона на момент решения**, а не против вскрытых карт:
верный вход, проигравший по случайности, ошибкой не является. Карты оппонентов
этот модуль не читает вообще — ни из `dealt`, ни из `showdowns`.

Вердикты в chip-EV (bb). ICM в v1 не применяется: в hand history GG нет призовой
структуры, а считать поправку не из чего — инструмент `icm_equities` ждёт
источника выплат.

**Анте стола входит в решаемую игру.** Продукт заявлен для MTT с анте, и брать
равновесие игры без анте значило бы судить не ту раздачу: на фикстуре семь анте
по 0.125bb дают 0.875bb мёртвых денег сверх 1.5bb блайндов, и равновесие без них
на 10bb теснее на 12.4 п.п. комбо по пушу и на 13.8 п.п. по коллу. Теснее — значит
верные шовы помечались бы ошибкой, а для тренажёра ложное обвинение хуже
пропущенной ошибки: оно учит пасовать там, где надо входить. Поэтому `nash_hu`
получает `dead_extra_bb` (сумма анте стола), а глубину — уже за вычетом анте.

**Правило зоны.** Точный расчёт есть только там, где диапазон не угадан:
хедз-ап SB против BB решается равновесием `nash_hu`. При трёх и более живых
диапазоны берутся из равновесия N-игроковой подыгры
(`analysis/tools/multiway.py`) — в неоткрытом банке это колл-диапазоны игроков
позади героя, против чужого шова это диапазон самого шовера и коллы тех, кто
сидел позади него, — но равновесие там не доказано, а измерено: вместе с
профилем решатель отдаёт его эксплуатируемость. Поэтому вывод обязан
быть помечен как опирающийся на модель — если только он от неё не зависит.
Последнее и проверяет bracket-тест: EV пересчитывается на СЕТКЕ ширин
колл-диапазона, и зона `strict` ставится, только когда вердикт одинаков на всех
её точках и совпадает с вердиктом самой модели. Опрашивается вся сетка, а не два
конца: EV по ширине не обязана быть монотонной — на прежней (вчетверо более
широкой) полосе вердикт переворачивался ВНУТРИ интервала на 2 точках сетки из
58 на обеих фикстурах. На калиброванной полосе (`_CALL_WIDTH_BAND`) такого не
встретилось ни разу, но 58 точек — не доказательство монотонности, и опрос
остаётся страховкой. Ошибка, которую правило предотвращает,
ровно одна и односторонняя: объявить устойчивым вывод, который на деле держится
на догадке, значит переоценить собственную уверенность. Решение о зоне целиком
живёт в `zone_for` — снаружи его переопределить негде.

**Живые игроки за героем при колле шова.** `call_shove_ev_bb` считает вскрытие
один на один, поэтому вход живых позади в модель не входит. Он считается второй
осью вилки (`ev_call_all_behind_bb`) и попадает в `zone_for`: если вердикт от неё
меняется, зона `assuming`, а цена берётся по самому мягкому из двух сценариев.
Когда два сценария дают разный оптимум, цена по этому правилу равна нулю, и
`best_action` называет развилку вместо одного действия (`_BEST_DEPENDS_ON_BEHIND`).
Живой БЕЗ фишек за спиной так не считается — его вход не развилка, и такая точка
остаётся без вердикта (см. границы ниже).

**Границы применимости, за которыми вердикта нет.** Модель описывает ровно две
формы: «шов или пас в неоткрытый банк» и «колл или пас против ОДНОГО открытого
шова». Всё остальное возвращается без вердикта с названной причиной
(`unpriced_reason`) — глубже 15bb, лимп, война повышений, ре-шов поверх чужого
опена, больше одного олл-ина в руке помимо героя, уже ответивший на шов перед
героем, живой без фишек за спиной помимо героя — и в шове в неоткрытый банк, и
в колле шова. Каждая граница снимает
вердикт целиком, а не поправляет число: инструмент описывает одну форму, и вне её
поправлять в нём нечего.

**Что снимает вердикт с уже посчитанной точки, а что меняет его форму.**
Снимает одно — контрольная сумма модели стола (`_model_checksum`): когда по
модели коллеров выходит, что шов почти наверняка ответят, модель описывает не
этот стол, и цену шова по ней не называем. Посчитанные числа остаются в
`detail` снятой точки, игроку не показывается ничего: `best_action` пуст, и
`error_cost.is_judged` такую точку не берёт.

Форму меняет ЗНАК интервала EV по моделям диапазона (`EvInterval`). Пока обе
границы по одну сторону нуля, вердикт обычный, и ширина интервала на него не
влияет. Когда интервал лежит по обе стороны нуля, точечной оценки нет — но и
отказа нет: точка получает вердикт `_BOTH_ACCEPTABLE` («около нуля»), интервал
и потолок цены ошибки, а цену ноль. Прежде такая точка отказывалась целиком
(«одного надёжного числа здесь нет»), и вместе с числом от игрока пропадали
знак, порядок величины и потолок цены — то есть всё, что у нас на неё есть.

**Фолд-эквити.** `shove_ev_bb` гейта не ставит (сигнатура заморожена задачей 11),
поэтому он стоит здесь: `fold_equity_ok` считается для каждого шова и попадает в
`detail`. Сама EV посчитана верно в любом случае — ветка «все сфолдили» получает
свою (нулевую) вероятность, — но изложение (задача 21) не имеет права объяснять
шов словами «оппоненты сфолдят», когда фолда в модели не существует.
"""

