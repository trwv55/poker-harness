class PgLimiterTimeout(Exception):
    """Окно темпа или слот одновременности не открылись до дедлайна (fix round
    1, Important 2; дедлайн — общий на всю цепочку ретраев с round 3, Item 1)
    — явная ошибка вместо вечного молчаливого ожидания, из которого снаружи
    никак не отличить нормальную очередь под нагрузкой от структурной поломки
    (например, утёкший лок, который самолечение при следующем чекауте того же
    физического соединения ещё не успело подобрать). Сообщение называет три
    вещи: какой именно механизм — темп или одновременность — не открылся, сколько
    реально ждали, и сколько бюджета оставалось на момент начала этого ожидания
    (fix round 4, Item 2) — без последнего после round 3 (общий дедлайн вместо
    отсчёта на попытку) неразличимы "эта попытка унаследовала уже почти
    исчерпанный бюджет" и "простояли все 120с с нуля, ничего не двигалось"."""


def _jitter() -> float:
    return random.uniform(_JITTER_MIN_S, _JITTER_MAX_S)


def _engine_of(session_factory: async_sessionmaker[AsyncSession]) -> AsyncEngine:
    """`session_factory.kw["bind"]` — тот же приём, что `db_factory` в
    `conftest.py`, но `sessionmaker.kw` типизирован SQLAlchemy как `dict[str,
    Any]` — pyright не может подтвердить отсюда, что это именно `AsyncEngine`
    (fix round 2, Item 4). Явная проверка — не формальность: если когда-нибудь
    `PgLimiter` создадут от sessionmaker'а без движка или с другим `bind`,
    лучше `TypeError` здесь, в конструкторе, чем `AttributeError` тремя
    уровнями глубже внутри `slot()` на первом же вызове.
    """
    engine = session_factory.kw["bind"]
    if not isinstance(engine, AsyncEngine):
        raise TypeError(
            f"session_factory.kw['bind'] — не AsyncEngine, а {type(engine)!r}"
        )
    return engine


class PgLimiter:
    """Пул из `max_concurrency` слотов плюс окно `max_per_minute` вызовов в минуту,
    оба — над `session_factory` (задача 14: тот же `async_sessionmaker`, что и у
    `JobsQueue`, `db_factory` в тестах) — конструктор принимает именно его, для
    единообразия с `JobsQueue`/`LLM`, хотя внутри `slot()` работает не с ним, а
    с движком (`_engine_of`, см. выше): нужно сырое `AsyncConnection` с
    `AUTOCOMMIT`, не ORM-сессию (см. модульный докстринг, "Пиннинг соединения").
    """

    def __init__(
        self,
        session_factory: async_sessionmaker[AsyncSession],
        *,
        max_concurrency: int,
        max_per_minute: int,
    ) -> None:
        self._engine = _engine_of(session_factory)
        self._max_concurrency = max_concurrency
        self._max_per_minute = max_per_minute

    @asynccontextmanager
    async def slot(self, *, deadline: float | None = None) -> AsyncIterator[None]:
        """Выделенное соединение на всё время удержания слота, закреплённое БЕЗ
        открытой транзакции (`AUTOCOMMIT` — см. модульный докстринг). Порядок —
        сначала самолечение, потом темп, потом одновременность (бриф задачи 16:
        "сначала темп, потом одновременность" — самолечение добавлено round 1
        перед обоими, иначе унаследованный чужой лок мог бы исказить оба опроса
        не только одновременности).

        `deadline` — абсолютный `time.monotonic()`-порог, общий на всю
        цепочку ретраев одного логического вызова (fix round 3, Item 1; см.
        модульный докстринг и `LLM.__call__`, который считает его один раз).
        Не передан — собственный свежий бюджет `_ACQUIRE_TIMEOUT_S`, как было
        до round 3 (прямой вызов `slot()` в обход `LLM`).
        """
        effective_deadline = (
            deadline if deadline is not None else time.monotonic() + _ACQUIRE_TIMEOUT_S
        )
        conn = await self._engine.connect()
        conn = await conn.execution_options(isolation_level="AUTOCOMMIT")
        try:
            # Important 1: любой advisory-лок, оставшийся на ЭТОМ физическом
            # соединении от предыдущего держателя, — заведомо чужой и заведомо
            # брошенный (пул не мог бы выдать соединение, которое кто-то ещё
            # держит живым) — см. модульный докстринг.
            await conn.execute(_UNLOCK_ALL_SQL)
            await self._wait_for_rate_window(conn, effective_deadline)
            slot_index = await self._acquire_advisory_lock(conn, effective_deadline)
            try:
                yield
            finally:
                # fix round 2, Item 1: НИЧЕГО отсюда не поднимается наружу —
                # ни `false` от `pg_advisory_unlock`, ни исключение из самого
                # вызова (соединение оборвалось) — только громкий лог. См.
                # модульный докстринг: `raise` здесь подменял бы исход тела
                # `yield`, вплоть до превращения оплаченного успеха в ошибку.
                try:
                    released = await conn.scalar(
                        _UNLOCK_SQL, {"cls": _ADVISORY_LOCK_CLASS, "idx": slot_index}
                    )
                    if not released:
                        logger.error(
                            "PgLimiter: pg_advisory_unlock(%s, %s) вернул false — "
                            "слот, который держало это соединение, свободным к "
                            "моменту освобождения не значился; самолечение снимет "
                            "утечку на следующем чекауте этого соединения",
                            _ADVISORY_LOCK_CLASS,
                            slot_index,
                        )
                except Exception:
                    logger.exception(
                        "PgLimiter: pg_advisory_unlock(%s, %s) сам упал — "
                        "соединение могло оборваться; самолечение снимет утечку "
                        "на следующем чекауте этого соединения",
                        _ADVISORY_LOCK_CLASS,
                        slot_index,
                    )
        finally:
            await conn.close()

    async def _wait_for_rate_window(self, conn: AsyncConnection, deadline: float) -> None:
        """`deadline` — общий бюджет всей цепочки ретраев (fix round 3, Item 1),
        не свежий отсчёт от входа в эту функцию — см. `slot()`/модульный
        докстринг.

        `started` — момент входа именно в ЭТУ функцию, не в весь `LLM.__call__`
        (у которого свои часы — `deadline`). Разница между ними —
        `deadline - started`, сколько бюджета ОСТАВАЛОСЬ на момент, когда это
        ожидание начиналось, — идёт в текст исключения (fix round 4, Item 2):
        без неё оператор не может отличить "эта попытка унаследовала уже почти
        исчерпанный бюджет (например, из-за медленного ответа модели на
        предыдущей попытке)" от "лимитер простоял все 120с с нуля, ничего не
        двигалось" — с round 3 (`deadline`, не собственный отсчёт на попытку)
        сообщение `"... не освободилось до дедлайна"` перестало называть число
        и эту разницу стало не различить.
        """
        started = time.monotonic()
        last_log = started
        while True:
            count = await conn.scalar(_RATE_WINDOW_SQL)
            if count is not None and count < self._max_per_minute:
                return
            now = time.monotonic()
            if now >= deadline:
                raise PgLimiterTimeout(
                    f"темп: окно ({self._max_per_minute}/мин) не освободилось — "
                    f"ждали {now - started:.1f}с, в начале ожидания в общем бюджете "
                    f"оставалось {deadline - started:.1f}с"
                )
            if now - last_log >= _STALL_LOG_INTERVAL_S:
                logger.warning(
                    "PgLimiter: жду окно темпа (%s/мин), осталось %.0fс до дедлайна",
                    self._max_per_minute,
                    deadline - now,
                )
                last_log = now
            await _sleep(min(_jitter(), max(0.0, deadline - now)))

    async def _acquire_advisory_lock(self, conn: AsyncConnection, deadline: float) -> int:
        """`deadline` — тот же общий бюджет, что у `_wait_for_rate_window`
        (fix round 3, Item 1): если темп уже съел большую часть бюджета,
        одновременности достаётся то, что осталось, а не новый полный отсчёт.

        `started`/сообщение исключения — тот же приём и то же обоснование, что
        у `_wait_for_rate_window` (fix round 4, Item 2): без разницы
        `deadline - started` оператор не отличит унаследованный почти пустой
        бюджет от честного простоя с нуля.
        """
        started = time.monotonic()
        last_log = started
        while True:
            for slot_index in range(self._max_concurrency):
                acquired = await conn.scalar(
                    _TRY_LOCK_SQL, {"cls": _ADVISORY_LOCK_CLASS, "idx": slot_index}
                )
                if acquired:
                    return slot_index
            now = time.monotonic()
            if now >= deadline:
                raise PgLimiterTimeout(
                    f"слот одновременности: ни один из {self._max_concurrency} не "
                    f"освободился — ждали {now - started:.1f}с, в начале ожидания в "
                    f"общем бюджете оставалось {deadline - started:.1f}с"
                )
            if now - last_log >= _STALL_LOG_INTERVAL_S:
                logger.warning(
                    "PgLimiter: жду слот одновременности (K=%s), осталось %.0fс до дедлайна",
                    self._max_concurrency,
                    deadline - now,
                )
                last_log = now
            await _sleep(min(_jitter(), max(0.0, deadline - now)))
