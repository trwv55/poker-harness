"""ICM (Independent Chip Model) по модели Малмута-Харвилла.

Переводит стеки в турнире в доли призового фонда. Идея: вероятность занять
1-е место пропорциональна доле стека от общего числа фишек на столе;
вероятность занять 2-е место — это вероятность занять "1-е" среди оставшихся
игроков при условии, что настоящее 1-е место занял кто-то другой, и так
рекурсивно для каждого следующего платного места. Итоговая доля игрока —
сумма по местам от (вероятность занять место k) * (выплата за место k).

Реализация — рекурсия с мемоизацией по множеству оставшихся игроков, а не
перебор всех перестановок порядка финиша (n! непригодно как рабочий код;
перебор используется только как независимый оракул в тесте). Для K платных
мест и n игроков сложность ограничена O(n^K), а не O(n!): при K <= 4 и
n <= 9 (наш верхний предел использования) это доли миллисекунды.
"""

from __future__ import annotations

from functools import cache

_MAX_PAID_PLACES = 4


def icm_equities(stacks: list[int], payouts: list[float]) -> list[float]:
    """Доля призового фонда для каждого игрока по модели Малмута-Харвилла.

    `payouts` — выплаты по местам (индекс 0 — приз за 1-е место), по убыванию;
    `len(payouts) <= len(stacks)` и не больше `_MAX_PAID_PLACES`. Сумма
    возвращённых долей равна `sum(payouts)` с точностью 1e-9 — это следует
    из того, что вероятности занять каждое место в сумме по игрокам дают 1.

    Стек <= 0 в списке — ошибка вызова, а не вырожденный нуль на выходе:
    игрок с нулевым стеком уже выбыл из турнира и не должен передаваться
    сюда. Помимо смысловой некорректности (выбывший не может "занять место"
    наравне с живыми), это ещё и математическая необходимость: если бы
    в списке было несколько нулевых стеков, при попытке распределить между
    ними места после того, как все игроки с фишками уже заняли более
    высокие места, знаменатель "доля от оставшегося стека" стал бы 0/0 —
    неопределённостью без единственно верного соглашения (равные доли по
    числу оставшихся? undefined?). Явный ValueError на входе снимает вопрос
    вместо того, чтобы молча подставлять произвольное соглашение.
    """
    n = len(stacks)
    if n == 0:
        raise ValueError("список стеков не может быть пустым")
    if any(s <= 0 for s in stacks):
        raise ValueError(
            "все стеки должны быть положительными: стек <= 0 означает выбывшего "
            f"игрока, не включайте его в список стеков (получено {stacks})"
        )
    if len(payouts) > _MAX_PAID_PLACES:
        raise ValueError(
            f"поддерживается не более {_MAX_PAID_PLACES} платных мест, получено "
            f"{len(payouts)} — передайте хвост релевантной призовой структуры стола"
        )
    if len(payouts) > n:
        raise ValueError(
            f"платных мест ({len(payouts)}) не может быть больше числа игроков ({n})"
        )

    full = frozenset(range(n))

    @cache
    def first_place_probs(remaining: frozenset[int]) -> tuple[tuple[int, float], ...]:
        """P(игрок i занимает 1-е место среди `remaining`) для каждого i в `remaining`.

        Стеки в `stacks` гарантированно положительны (проверено на входе),
        поэтому сумма по любому непустому подмножеству строго больше нуля —
        деления на ноль здесь не бывает.
        """
        pool = sum(stacks[i] for i in remaining)
        return tuple((i, stacks[i] / pool) for i in remaining)

    @cache
    def place_dist(remaining: frozenset[int], place: int) -> tuple[tuple[int, float], ...]:
        """P(игрок i занимает абсолютное место `place`) для каждого i в `remaining`.

        База (place == 1): напрямую доля стека. Иначе — сумма по кандидатам j
        на предыдущее (более высокое) место: P(j впереди) * P(i на месте
        `place` среди оставшихся после того, как j выбыл).
        """
        if place == 1:
            return first_place_probs(remaining)
        totals: dict[int, float] = dict.fromkeys(remaining, 0.0)
        for leader, p_leader in first_place_probs(remaining):
            for i, p_rest in place_dist(remaining - {leader}, place - 1):
                totals[i] += p_leader * p_rest
        return tuple(totals.items())

    equities = [0.0] * n
    for place, payout in enumerate(payouts, start=1):
        for i, prob in place_dist(full, place):
            equities[i] += prob * payout

    return equities
