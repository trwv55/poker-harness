"""Общий предок схем, которые заполняет модель: разворот конверта и строгость.

Схема вывода — единственное место, где ответ модели превращается в данные, и у
этого превращения есть измеренный класс отказа, который система однажды не
заметила (догфудинг 2026-09-11).

**Конверт.** Модель кладёт заполненную схему внутрь ОДНОГО контейнерного ключа
вместо раскладки по корню. Имя ключа плавает от вызова к вызову (`params`,
`$PARAMETER_NAME`), поэтому сравнение с конкретной строкой ничего не закрывает;
признак — сама форма: единственный ключ, которого нет среди полей схемы, а его
значение — объект. Такой ответ разворачивается ДО валидации полей.

**Строгость.** Схемы вывода состоят из необязательных полей, и это осознанно:
пустое поле честнее выдуманного. Цена решения ровно здесь — объект, в котором не
распознано НИ ОДНО поле, валиден и пуст. Пустота же в системе означает «модель
ничего не увидела» и лечится повтором: зрение платит за вторую попытку и за
дорогую ступень каскада, получая тот же результат, потому что причина не в
модели, а в форме. `extra="forbid"` превращает эту тихую потерю в ошибку
валидации — её ловит схема-ретрай фасада (спека §7) и видно в `llm_calls`
статусом `schema_error`, а не `ok` с полутора тысячами выброшенных токенов.

Строгость и разворот стоят рядом не случайно: разворот закрывает ИЗВЕСТНУЮ форму
отказа, `forbid` — все остальные, ещё не встреченные, и без него следующая
такая находка снова стоила бы вечера раскопок вместо строки в логе.
"""

from __future__ import annotations

from typing import Any, cast

from pydantic import ConfigDict, model_validator

__all__ = ["ModelOutput"]


class ModelOutput:
    """Примесь к схемам, которые заполняет LLM (по одной на каждое её место).

    Примесь, а не базовая модель, и это не стилистика: `BaseModel` обязан
    остаться прямой базой самой схемы. Иначе статический анализ перестаёт узнавать
    в ней pydantic-модель и требует `ClassVar` для умолчаний-списков — то есть
    правку десятка полей ради одного наследования. Pydantic собирает и
    `model_config`, и валидаторы по всему MRO, поэтому примесь работает наравне
    с базой (`tests/test_contracts.py`, разворот конверта на всех четырёх схемах).
    """

    model_config = ConfigDict(extra="forbid")

    @model_validator(mode="before")
    @classmethod
    def _unwrap_container(cls, data: Any) -> Any:
        """Спустить на этаж ниже, если весь ответ завёрнут в один чужой ключ."""
        if not isinstance(data, dict):
            return data
        fields = cast("dict[str, Any]", data)
        if len(fields) != 1:
            return fields
        key, value = next(iter(fields.items()))
        known: dict[str, Any] = getattr(cls, "model_fields", {})
        if key in known or not isinstance(value, dict):
            return fields
        return cast("dict[str, Any]", value)
